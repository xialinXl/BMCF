function [Keypoint_Image,gradient_1,angle] = KeypointDetectionImage(Filter_img,Edge_Image,scale_ratio,sigma_initial,layer)
    [M,N] = size(Edge_Image);
    Keypoint_Image=zeros(M,N);
    gradient_1=zeros(M,N);
    angle=zeros(M,N);
    cur_scale=sigma_initial*scale_ratio^(layer-1);
    h1=[-1,0,1;-2,0,2;-1,0,1];
    h2=[-1,-2,-1;0,0,0;1,2,1];
    gradient_x_1=imfilter(Edge_Image,h1,'replicate');
    gradient_y_1=imfilter(Edge_Image,h2,'replicate');
    gradient_1=sqrt(gradient_x_1.^2 + gradient_y_1.^2);
    angle=atan2(gradient_y_1,gradient_x_1);
    angle=angle*180/pi;
    angle(angle<0)=angle(angle<0)+360;
    Csh_11=cur_scale^2*gradient_x_1.*gradient_x_1;
    Csh_12=cur_scale^2*gradient_x_1.*gradient_y_1;
    Csh_22=cur_scale^2*gradient_y_1.*gradient_y_1;
    gaussian_sigma=cur_scale*sqrt(2);
    temp=round(2*gaussian_sigma);
    gaussian_width=2*temp+1;
    W=fspecial('gaussian',[gaussian_width,gaussian_width],gaussian_sigma);
    [a,b]=meshgrid(1:gaussian_width,1:gaussian_width);
    index=((a-temp-1)^2+(b-temp-1)^2)>temp^2;
    W(index)=0;
    Csh_11=imfilter(Csh_11,W,'replicate');
    Csh_12=imfilter(Csh_12,W,'replicate');
    Csh_22=imfilter(Csh_22,W,'replicate');
    Variance = stdfilt(Filter_img, ones(3)).^2;
    local_sum = conv2(Filter_img, ones(3), 'same');
    average = local_sum./9;
    Local_difference = abs(Filter_img - average);
    Local_difference_2 = Local_difference.^2;
    local_variance = exp((Local_difference_2./(Variance))./9);
    T=Csh_11+Csh_22;
    D=Csh_11.*Csh_22-Csh_12.^2;
    sqrt_arg = max((T/2).^2 - D, 0);
    lambda1=(T/2)-sqrt(sqrt_arg); 
    lambda2=(T/2)+sqrt(sqrt_arg); 
    Variance_1 = stdfilt(real(lambda1), ones(3)).^2;
    Variance_2 = stdfilt(real(lambda2), ones(3)).^2;
    dir_weight_1 = Variance_1./max(Variance_1(:));
    dir_weight_2 = Variance_2./max(Variance_2(:));  
    lambda1 = dir_weight_1 .* lambda1;
    lambda2 = dir_weight_2 .* lambda2;
    Keypoint_Image = min(lambda1,lambda2);
end